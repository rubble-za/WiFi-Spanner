#!/usr/bin/env python3
"""Writes THIRD-PARTY-LICENSES.txt: every third-party crate the Linux build
uses, with its licence expression and the licence texts found in its source,
grouped so identical texts are printed once.

Run from the repository root after `cargo fetch`:
    python3 -I packaging/third-party-licenses.py
"""
import hashlib, json, os, re, subprocess, sys

OURS = {"wifispanner-app", "wifispanner-core", "wifispanner-scan", "wifispanner-spike"}
NAME = re.compile(r"(licen[sc]e|copying|notice|unlicense|^ofl|^ufl|copyright)", re.I)
SKIP_DIRS = {"src", "tests", "test", "examples", "benches", "target", ".git"}

meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", "x86_64-unknown-linux-gnu"]))
resolved = {n["id"] for n in meta["resolve"]["nodes"]}
crates = sorted((p for p in meta["packages"] if p["id"] in resolved and p["name"] not in OURS),
                key=lambda p: (p["name"], p["version"]))

groups = {}   # text hash -> (text, [crate labels])
no_text = []
for p in crates:
    root = os.path.dirname(p["manifest_path"])
    found = []
    for dirpath, dirs, files in os.walk(root):
        depth = dirpath[len(root):].count(os.sep)
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS and depth < 2]
        for f in files:
            if NAME.search(f) and not f.endswith((".rs", ".toml", ".json", ".md.in")):
                path = os.path.join(dirpath, f)
                try:
                    text = open(path, encoding="utf-8", errors="replace").read().strip()
                except OSError:
                    continue
                if 40 < len(text) < 200_000:
                    found.append(text)
    label = f'{p["name"]} {p["version"]} ({p.get("license") or "see source"})'
    if not found:
        no_text.append(label)
    for text in found:
        h = hashlib.sha256(text.encode()).hexdigest()
        groups.setdefault(h, (text, []))[1].append(label)

out = ["WiFi Spanner: third-party licences",
       "",
       "WiFi Spanner includes the libraries below (and the fonts and data files they",
       "embed) under the licences shown. Generated by packaging/third-party-licenses.py.",
       "",
       f"{len(crates)} libraries. Licence texts follow, each printed once with the",
       "libraries it applies to.", ""]
for text, labels in sorted(groups.values(), key=lambda g: g[1][0]):
    out += ["=" * 78, "Applies to:"]
    out += ["  " + l for l in sorted(set(labels))]
    out += ["-" * 78, text, ""]
# Fonts and icons bundled in the app's own sources rather than through a library. Their full
# licence texts are kept in packaging/licenses/ and printed here.
here = os.path.dirname(os.path.abspath(__file__))
def bundled(applies, intro, path):
    text = open(os.path.join(here, "licenses", path), encoding="utf-8").read().strip()
    return ["=" * 78, "Applies to:", "  " + applies, "-" * 78, intro, "", text, ""]
out += bundled(
    "IBM Plex Sans (crates/wifispanner-app/assets/fonts: Regular, Medium, SemiBold)",
    "IBM Plex is Copyright (c) 2017 IBM Corp. with Reserved Font Name \"Plex\" (the font files\n"
    "themselves say 2018). The files are used unmodified, under the SIL Open Font License 1.1, whose\n"
    "text follows as published at https://github.com/IBM/plex.",
    "IBM-Plex-OFL-1.1.txt")
out += bundled(
    "IBM Carbon icons (crates/wifispanner-app/assets/carbon-icons: 34 icons)",
    "The icons are from the IBM Carbon Design System (https://github.com/carbon-design-system/carbon,\n"
    "packages/icons), Copyright IBM Corp., under the Apache License 2.0, whose text follows as published\n"
    "in that repository. CHANGES: each icon was rasterised to a 96 x 96 pixel image and recoloured white\n"
    "on a transparent background; the original SVG files are kept unmodified alongside them.",
    "Carbon-Icons-Apache-2.0.txt")
if no_text:
    out += ["=" * 78, "Libraries whose licence is stated in their metadata but that ship no separate",
            "licence file (the named licence applies):"]
    out += ["  " + l for l in no_text]
sys.stdout.write("\n".join(out) + "\n")
